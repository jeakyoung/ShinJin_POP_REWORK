import assert from 'node:assert/strict'

export async function verifyPicker({login, run, cdp, tap, click, shown, until, url, save, qs, btn, scan, version}) {
  await login('DEMO-A','DEMO-W01')
  await until(()=>run("fetch('/api/pop/session').then(r=>r.ok)"),'authenticated')
  const slot = Number(process.env.PICKER_SLOT ?? 1)
  const identity = await run("fetch('/api/pop/session').then(r=>r.json())")
  if(slot===2) {
    assert.deepEqual(identity.processSlots,[2])
    await tap(btn('메뉴 복귀'))
    await until(()=>run('!!'+qs('button[data-slot="2"]')),'production slots')
    assert.equal(await run(`document.querySelector('button[data-slot="1"]').disabled`),true)
    assert.equal(await run(`document.querySelector('button[data-slot="2"]').disabled`),false)
    await save('real-menu-slot2')
    await tap(qs('button[data-slot="2"]'));await shown('DEMO-ORDER-11')
  }
  await cdp('Page.navigate',{url:url+'/picker.html?slot='+slot})
  const path='/api/pop/work-orders/2026-11-25/101/stock-picker'
  const http=(path,body,method='POST')=>run(`fetch(${JSON.stringify(path)},{method:${JSON.stringify(method)},headers:{'Content-Type':'application/json'},body:${JSON.stringify(JSON.stringify(body))}}).then(async r=>[r.status,r.ok?await r.json():null])`)
  const detail=()=>run("fetch('/api/pop/work-orders/2026-11-25/101').then(r=>r.json())")
  const before=await detail()
  assert.equal((await http(path+'/fixed?slot='+slot,{role:'auxiliary',code:'UNASSIGNED'},'PUT'))[0],403)
  assert.equal((await http(path+'/remnants?slot=6',{}))[0],403)
  assert.deepEqual((await http(path.replace('/101/','/102/')+'/remnants?slot='+slot,{}))[1],{eligible:false,rows:[]})
  const picker=qs('.pl-select'), notice=qs('.pl-notice')
  const entries = () => run("document.querySelectorAll('.pl-left tbody tr').length")
  const parent=()=>run("[...document.querySelectorAll('[data-process-lot]')].map(r=>[r.dataset.processLot,r.cells[6].textContent])")
  await click('수동 선택');await until(async()=>await entries()===1,'manual main stock')
  const rect = sel => run(`(()=>{const r=document.querySelector(${JSON.stringify(sel)}).getBoundingClientRect();return [r.x,r.y,r.width,r.height].map(Math.round)})()`)
  assert.deepEqual((await rect('.pl-select')).slice(2),[1280,831])
  assert.deepEqual((await rect('.pl-remnant')).slice(2),[133,70])
  await save('manual-open')
  await tap(btn('투입보조'));await shown('창고코드');await save('aux-open')
  await tap(qs('.pl-options [role=option]'));await until(()=>run("!!document.querySelector('[aria-label=\"WH-A2 BIN-02 추가\"]')"),'aux stock')
  await tap(btn('WH-A2 BIN-02 추가'))
  await click('스캔으로 수량 추가하기',picker);await scan('SYNAUX0001');await until(()=>run("document.querySelector('.pl-right tbody tr')?.cells[6]?.innerText==='2'"),'continued scan')
  await click('닫기',qs('.pl-inline'))
  await tap(btn('위치 바코드 스캔'))
  const input=qs('dialog[aria-label="Location 바코드를 스캔하세요."] input')
  await until(()=>run('document.activeElement==='+input),'location focus')
  assert.deepEqual(await rect('dialog[aria-label="Location 바코드를 스캔하세요."]'),[70,490,880,300])
  await save('location-open')
  await scan(' LAB-LOCATION');await shown('등록되지 않은 Location입니다.');await click('확인',notice)
  await until(()=>run('document.activeElement==='+input),'location retry')
  await scan('LAB-LOCATION');await shown('합성 위치 가')
  // frmProcess1 does not pass the scanned location to SELECT; a later refresh uses the primary editor (blank after aux).
  await until(async()=>await entries()===0,'primary empty lookup')
  await click('잔재 추가',picker);await until(()=>run(`document.querySelector('.pl-right').innerText.includes('${slot===2?'REM-STD':'REM-CUT'}')`),'manual SELECT2')
  await click('잔재 추가',picker);await click('잔재 추가',picker);await shown('투입수량이 재고 수량보다 높을 순 없습니다.');await click('확인',notice)
  await save('manual-remnants')
  await click('적용',picker);await until(async()=>(await parent()).length===2,'return picks')
  assert.deepEqual(await parent(),[['SYNAUX0001','2'],[slot===2?'SYNREM0003':'SYNREM0007','2']])
  await click('수동 선택');await until(async()=>await entries()===1,'restored fixed auxiliary code')
  await tap(btn('투입창고'));await tap(qs('.pl-options [role=option]'));await until(()=>run("!!document.querySelector('[aria-label=\"WH-A BIN-01 추가\"]')"),'main reselected')
  await click('닫기',picker)
  await click('LOT 스캔');await until(()=>run('!!document.querySelector(".common-scan-dialog input")'),'material scan')
  await scan('LOT-A-01');await until(async()=>await entries()===3,'auto subset')
  await until(()=>run('!document.querySelector(".pl-remnant").disabled'),'metadata')
  assert.equal(await run("document.querySelector('button[aria-label=투입창고]').disabled"),true)
  assert.equal(await run("document.querySelector('.pl-scan').disabled"),true)
  await tap(btn('투입보조'));await tap(qs('.pl-options [role=option]'))
  await until(()=>run('!document.querySelector(".pl-remnant").disabled'),'auto auxiliary changed')
  assert.equal(await entries(),3)
  await tap(qs('.pl-left tbody tr:nth-child(2) td:first-child'))
  await click('잔재 추가',picker);assert.equal(await run("document.querySelector('.pl-right tbody tr').cells[1].textContent"),'BIN-02')
  await save('auto-focused')
  await click('닫기',picker);assert.deepEqual(await parent(),[['SYNAUX0001','2'],[slot===2?'SYNREM0003':'SYNREM0007','2']])
  assert.deepEqual(await detail(),before)
  console.log(version.Browser+' PASS 1280x1024: manual auxiliary stock, raw location failure/success, manual SELECT2 and overflow, fixed selection, auto focused stock and preserved subset, cancel/parent result, server inventory unchanged.')
}
